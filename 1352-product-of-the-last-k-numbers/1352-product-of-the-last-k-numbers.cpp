class ProductOfNumbers {
public:
    vector<int>nums;
    ProductOfNumbers() {
        
    }
    
    void add(int num) {
        nums.push_back(num);
    }
    
    int getProduct(int k) {
        int n=nums.size();
        int curr=k;
        int i=0;
        int ret=1;
        while(curr--){
            ret=ret*nums[n-1-i];
            i++;
        }
        return ret;
    }
};

